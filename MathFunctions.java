import java.util.*;
public class MathFunctions
{
    public static void main(double num1,double num2)
    {
        System.out.println("Squ root:"+Math.sqrt(num1));
        System.out.println("Min:"+Math.min(num1,num2));
        System.out.println("Max:"+Math.max(num1,num2));
        System.out.println("pow of 3:"+Math.pow(num1,3));
        System.out.println("Log of base;"+Math.log(num1));
        System.out.println("Abs ;"+Math.abs(num2));
        System.out.println("Round;"+Math.round(num2));
        System.out.println("floor;"+Math.floor(num1));
        System.out.println("ceil;"+Math.ceil(num1));
        System.out.println("Rint;"+Math.rint(num1));
        System.out.println("Exponet val;"+Math.exp(num2));
        System.out.println("Cos 30;"+Math.cos(30));
        System.out.println("Sin 30;"+Math.sin(30));
        System.out.println("Tan 30;"+Math.tan(30));
        System.out.println("Random;"+Math.random());
    }
}